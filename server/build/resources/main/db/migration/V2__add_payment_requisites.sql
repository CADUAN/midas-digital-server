CREATE SEQUENCE IF NOT EXISTS payment_requisites_seq START WITH 1;

CREATE TABLE IF NOT EXISTS payment_requisites (
    user_id BIGINT PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,
    inn VARCHAR(32) NOT NULL UNIQUE,
    kpp VARCHAR(32) NOT NULL UNIQUE,
    bik VARCHAR(32) NOT NULL UNIQUE,
    account VARCHAR(32) NOT NULL UNIQUE,
    correspondent_account VARCHAR(32) NOT NULL UNIQUE,
    contract_number VARCHAR(32) NOT NULL UNIQUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
